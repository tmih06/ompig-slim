"""Generate the additional provider catalogs from the pinned personal source snapshot."""

import argparse
import json
import os

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", help="omp-slim packages/ai/src/providers/data directory")
parser.add_argument("output", nargs="?", default="vendor/github.com/MichaelKinsy/PiG/ai/providers_added_catalog.go")
args = parser.parse_args()
SRC = args.source
OUT = args.output

PROVIDERS = sorted("""aiand aimlapi alibaba-coding-plan alibaba-token-plan cline-pass commandcode
coralbricks deepinfra inception kilo modular ollama-cloud sambanova scaleway synthetic venice""".split())

LEVELS = {"off": "ThinkingOff", "minimal": "ThinkingMinimal", "low": "ThinkingLow",
          "medium": "ThinkingMedium", "high": "ThinkingHigh", "xhigh": "ThinkingXHigh",
          "max": "ThinkingMax"}

def gofloat(v):
    if v == 0:
        return "0"
    s = repr(float(v))
    if s.endswith(".0"):
        s = s[:-2]
    return s

def compat_literal(c):
    parts = []
    order = [
        ("supportsStore", "SupportsStore", "bool"),
        ("supportsDeveloperRole", "SupportsDeveloperRole", "bool"),
        ("supportsReasoningEffort", "SupportsReasoningEffort", "bool"),
        ("maxTokensField", "MaxTokensField", "str"),
        ("supportsStrictMode", "SupportsStrictMode", "bool"),
        ("supportsLongCacheRetention", "SupportsLongCacheRetention", "bool"),
        ("requiresReasoningContentOnAssistantMessages", "RequiresReasoningContentOnAssistantMessages", "bool"),
        ("thinkingFormat", "ThinkingFormat", "str"),
    ]
    assert not (set(c) - {key for key, _, _ in order}), c
    for key, field, kind in order:
        if key not in c:
            continue
        value = c[key]
        if kind == "bool":
            parts.append("%s: new(%s)" % (field, "true" if value else "false"))
        else:
            parts.append('%s: "%s"' % (field, value))
    return "{" + ", ".join(parts) + "}"

compats = {}
compat_literals = {}
compats_order = []
thinking = {}
thinking_order = []
inputs_limit = {}

def intern(store, order, key, factory):
    if key not in store:
        order.append(key)
        store[key] = factory(len(order) - 1)
    return store[key]

rows_by_provider = {}
for pid in PROVIDERS:
    data = json.load(open(os.path.join(SRC, pid + ".json")))
    rows = []
    for api_group, models in data.items():
        assert api_group == "openai-completions", (pid, api_group)
        for key, m in models.items():
            assert key == m["type"] + ":" + m["id"], (pid, key)
            assert m["type"] == "chat"
            record = json.dumps(m, separators=(",", ":"), ensure_ascii=False)
            compat = m.get("compat")
            compat_ref = "nil"
            if compat is not None:
                ck = json.dumps(compat, sort_keys=True)
                name = intern(compats, compats_order, ck,
                              lambda index, c=compat: "addedCompat%d" % index)
                compat_literals[name] = compat_literal(compat)
                compat_ref = "&" + name
            think_ref = ""
            if m.get("thinkingLevelMap"):
                tk = json.dumps(m["thinkingLevelMap"], sort_keys=True)
                name = intern(thinking, thinking_order, tk,
                              lambda index, t=m["thinkingLevelMap"]: "addedThinking%d" % index)
                think_ref = name
            limits_ref = "nil"
            if m.get("inputLimits"):
                assert m["inputLimits"] == {"images": {"resize": {
                    "maxWidth": 2000, "maxHeight": 2000,
                    "maxBytes": 4718592, "jpegQuality": 80,
                }}}, (pid, key, m["inputLimits"])
                lk = json.dumps(m["inputLimits"], sort_keys=True)
                inputs_limit[lk] = "addedInputLimitsImages"
                limits_ref = "&addedInputLimitsImages"
            cost = m["cost"]
            tiers = cost.get("tiers")
            rows.append({
                "id": m["id"], "name": m["name"], "api": m["api"], "base": m["baseUrl"],
                "compat": compat_ref, "thinking": think_ref, "limits": limits_ref,
                "context": m["contextWindow"], "max": m["maxTokens"],
                "input_cost": cost["input"], "output_cost": cost["output"],
                "cache_read": cost["cacheRead"], "cache_write": cost["cacheWrite"],
                "tiers": tiers, "reasoning": m["reasoning"], "input": m["input"],
                "record": record,
            })
    rows_by_provider[pid] = rows

total = sum(len(v) for v in rows_by_provider.values())

out = []
w = out.append
w("// Code generated by ompig-slim's catalog port (tooling over the catalog data of")
w("// packages/ai/src/providers/data/<provider>.json). DO NOT EDIT.")
w("//")
w("// Ports the 16 OpenAI-compatible providers OMP serves and this harness adds")
w("// (omp-slim commit 4b87440d7, catalogs regenerated from models.dev v2): every model")
w("// row, its cost, context window, output limit, thinking map, input limits and")
w("// compat flags, plus the catalog record each model serializes as.")
w("package ai")
w("")
w("import \"slices\"")
w("")
w("// addedProviderIDs lists the providers this file adds, in catalog order.")
w("var addedProviderIDs = []string{")
for pid in PROVIDERS:
    w('\t"%s",' % pid)
w("}")
w("")

if compats_order:
    w("// The compat bags the added catalogs refer to (shared, so one bag costs one value).")
for i, ck in enumerate(compats_order):
    w("var %s = ModelCompat%s" % (compats[ck], compat_literals[compats[ck]]))
if compats_order:
    w("")

if thinking_order:
    w("// The thinking level maps the added catalogs refer to.")
for i, tk in enumerate(thinking_order):
    mapping = json.loads(tk)
    parts = []
    for level in ["off", "minimal", "low", "medium", "high", "xhigh", "max"]:
        if level not in mapping:
            continue
        value = mapping[level]
        if value is None:
            parts.append("%s: nil" % LEVELS[level])
        else:
            parts.append('%s: new("%s")' % (LEVELS[level], value))
    w("var addedThinking%d = map[ModelThinkingLevel]*string{%s}" % (i, ", ".join(parts)))
if thinking_order:
    w("")

if inputs_limit:
    w("// addedInputLimitsImages is the cache-safe image resize every image-capable model of")
    w("// these catalogs carries.")
    w("var addedInputLimitsImages = ModelInputLimits{Images: &ModelImageInputLimits{Resize: &ModelImageResizeOptions{MaxWidth: 2000, MaxHeight: 2000, MaxBytes: 4718592, JPEGQuality: 80}}}")
    w("")

w("// addedProviderModels is the catalog of the added providers: %d chat models." % total)
w("var addedProviderModels = []GeneratedModel{")
for pid in PROVIDERS:
    for r in rows_by_provider[pid]:
        w("\t{")
        w('\t\tID:                   "%s",' % r["id"])
        w('\t\tProvider:             "%s",' % pid)
        w('\t\tDisplayName:          %s,' % json.dumps(r["name"], ensure_ascii=False))
        w('\t\tAPI:                  "%s",' % r["api"])
        w('\t\tBaseURL:              "%s",' % r["base"])
        w("\t\tCompat:               %s," % r["compat"])
        if r["thinking"]:
            w("\t\tThinkingLevelMap:     %s," % r["thinking"])
        w("\t\tInputLimits:          %s," % r["limits"])
        w("\t\tContextWindow:        %d," % r["context"])
        w("\t\tMaxOutputTokens:      %d," % r["max"])
        w("\t\tInputCostPerMTokens:  %s," % gofloat(r["input_cost"]))
        w("\t\tOutputCostPerMTokens: %s," % gofloat(r["output_cost"]))
        w("\t\tCacheReadCost:        %s," % gofloat(r["cache_read"]))
        w("\t\tCacheWriteCost:       %s," % gofloat(r["cache_write"]))
        if r["tiers"]:
            tier_parts = []
            for t in r["tiers"]:
                tier_parts.append("{InputTokensAbove: %s, InputCostPer1M: %s, OutputCostPer1M: %s, CacheReadCostPer1M: %s, CacheWriteCostPer1M: %s}" % (
                    gofloat(t["inputTokensAbove"]), gofloat(t["input"]), gofloat(t["output"]),
                    gofloat(t["cacheRead"]), gofloat(t["cacheWrite"])))
            w("\t\tTiers:                []CostTier{%s}," % ", ".join(tier_parts))
        w("\t\tReasoning:            %s," % ("true" if r["reasoning"] else "false"))
        w('\t\tCapabilities:         []string{%s},' % ", ".join('"%s"' % i for i in r["input"]))
        w("\t\tRecord:               %s," % json.dumps(r["record"], ensure_ascii=False))
        w("\t},")
w("}")
w("")
w("// registerAddedProviders adds the ported catalogs to the generated ones, so every")
w("// reader of GeneratedProviders and GeneratedModels (listing, lookup, --list-models,")
w("// the model registry and the remote catalog refresh) sees them.")
w("func init() {")
w("\tGeneratedModels = append(GeneratedModels, addedProviderModels...)")
w("\tadded := slices.Concat(GeneratedProviders, addedProviderIDs)")
w("\tslices.Sort(added)")
w("\tGeneratedProviders = slices.Compact(added)")
w("}")
w("")

open(OUT, "w").write("\n".join(out))
print("models:", total, "providers:", len(PROVIDERS))
print("lines:", len(out))
for pid in PROVIDERS:
    print(pid, len(rows_by_provider[pid]))
